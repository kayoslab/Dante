-- Calendar + absence normalization (phase: DB-level report support).
--
-- 1. `state_holiday` — German public holidays per state ('DE' = federal),
--    seeded 2024-2030 from the same `date-holidays` source the TS engines
--    use (lib/db/_de-holidays.ts). Working-day = Mon-Fri AND no holiday row
--    for the employee's state. Re-seed before 2031 (see scratchpad
--    generator in the PR / regenerate via germanHolidaysForState).
-- 2. `absence_day` — VIEW expanding absence ranges into weighted days,
--    mirroring expandAbsenceRows() in lib/db/_monthly-helpers.ts exactly:
--    half_day_start/end subtract 0.5 (floor 0.5), overlapping records take
--    MAX weight per day, unpaid = keyword match on time_off_type. The view
--    deliberately does NOT filter weekends/holidays — that filter is
--    state-dependent and happens at query time against state_holiday.
-- 3. `tracked_time_effective` — VIEW with the day-level awork/Personio
--    reconciliation + effective-billability rules from
--    lib/db/queries/tracked-hours.ts, so every consumer shares ONE
--    definition of "tracked time with billability".
CREATE TABLE "state_holiday" (
	"state" varchar(2) NOT NULL,
	"day" date NOT NULL,
	"name" text,
	CONSTRAINT "state_holiday_pk" PRIMARY KEY ("state", "day")
);
