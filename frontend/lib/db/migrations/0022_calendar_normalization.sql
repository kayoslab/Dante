CREATE VIEW "absence_day" AS
SELECT a.employee_id,
       d.dy::date AS day,
       MAX(x.weight) AS weight,
       COALESCE(MAX(x.weight) FILTER (WHERE x.is_unpaid), 0) AS unpaid_weight
FROM absence a
CROSS JOIN LATERAL generate_series(a.start_date::timestamp, a.end_date::timestamp, interval '1 day') AS d(dy)
CROSS JOIN LATERAL (
  SELECT CASE WHEN raw.w <= 0 THEN 0.5 ELSE raw.w END AS weight,
         lower(coalesce(a.time_off_type, '')) ~ '(unbezahlt|unpaid|elternzeit|parental leave|sabbatical)' AS is_unpaid
  FROM (SELECT 1.0
          - CASE WHEN d.dy::date = a.start_date AND a.half_day_start THEN 0.5 ELSE 0.0 END
          - CASE WHEN d.dy::date = a.end_date   AND a.half_day_end   THEN 0.5 ELSE 0.0 END AS w) raw
) x
GROUP BY a.employee_id, d.dy::date;
